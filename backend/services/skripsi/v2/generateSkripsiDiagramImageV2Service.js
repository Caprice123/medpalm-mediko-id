import fs from 'fs'
import os from 'os'
import path from 'path'
import prisma from '#prisma/client'
import { BaseService } from '#services/baseService'
import { ValidationError } from '#errors/validationError'
import { NotFoundError } from '#errors/notFoundError'
import { GeminiService } from '#services/ai/gemini.service'
import { GetConstantsService } from '#services/constant/getConstantsService'
import { checkAccessAndDeductCredit } from '#services/shared/checkAccessAndDeductCreditService'
import attachmentService from '#services/attachment/attachmentService'

const DEFAULT_IMAGE_MODEL = 'gemini-2.5-flash-image'
const UPLOAD_FOLDER = 'skripsi-diagrams'
const MAX_PROMPT_LENGTH = 1000

// What the student types is a topic ("patofisiologi crush syndrome"), not a
// drawing brief. This turns it into one, so the result reads like a textbook
// figure instead of an illustration.
const buildImagePrompt = (description) => [
  'Buat diagram edukatif untuk mahasiswa kedokteran berdasarkan permintaan berikut:',
  `"${description}"`,
  '',
  'Ketentuan gambar:',
  '- Gaya flowchart/diagram ilmiah yang bersih, bukan ilustrasi artistik.',
  '- Latar putih polos, garis dan panah tegas, kotak-kotak rapi.',
  '- Semua teks dalam Bahasa Indonesia, ejaan medis yang benar, huruf besar jelas dan mudah dibaca.',
  '- Tanpa watermark, tanpa logo, tanpa tangan atau figur manusia dekoratif.',
  '- Susun alurnya dari atas ke bawah agar mudah diikuti.',
].join('\n')

// The Diagram Builder generates a picture rather than a Mermaid/Excalidraw
// scene: the student gets a figure they can drop straight into the report.
//
// The image is stored the way every other file in this project is — uploaded as
// a blob and linked through the polymorphic attachments table — so the diagram
// row itself holds no URL.
export class GenerateSkripsiDiagramImageV2Service extends BaseService {
  static async call({ tabId, userId, description }) {
    const prompt = typeof description === 'string' ? description.trim() : ''

    if (!prompt) {
      throw new ValidationError('Deskripsi diagram wajib diisi')
    }

    if (prompt.length > MAX_PROMPT_LENGTH) {
      throw new ValidationError(`Deskripsi maksimal ${MAX_PROMPT_LENGTH} karakter`)
    }

    // Ownership is held by the report, not the tab, so it is checked through
    // the relation rather than on the tab row.
    const tab = await prisma.skripsi_tabs.findFirst({
      where: { id: parseInt(tabId) },
      include: { skripsi_set: true },
    })

    if (!tab || tab.skripsi_set.user_id !== userId) {
      throw new NotFoundError('Tab tidak ditemukan')
    }

    const constants = await GetConstantsService.call([
      'skripsi_access_type',
      'pbl_diagram_enabled',
      'pbl_diagram_cost',
      'pbl_diagram_image_model',
    ])

    if (constants.pbl_diagram_enabled !== 'true') {
      throw new ValidationError('Diagram Builder sedang tidak aktif')
    }

    await checkAccessAndDeductCredit(prisma, {
      userId,
      userRole: 'user',
      accessTypeKey: 'skripsi_access_type',
      creditCostKey: 'pbl_diagram_cost',
      // Matching the chat path, which checks access but has never charged.
      deductCredit: false,
      description: '',
      featureKey: 'skripsi_builder',
    })

    const model = constants.pbl_diagram_image_model || DEFAULT_IMAGE_MODEL
    const { buffer, mimeType } = await GeminiService.generateImage(model, buildImagePrompt(prompt))

    const diagram = await prisma.skripsi_diagrams.create({
      data: {
        tab_id: tab.id,
        diagram_type: 'image',
        description: prompt,
        // The column is required and belongs to the Excalidraw era; an image
        // diagram keeps its picture in the attachment instead.
        diagram_data: '',
        creation_method: 'ai_generated',
      },
    })

    const { blob } = await this.storeImage({ diagramId: diagram.id, buffer, mimeType })

    const stored = await attachmentService.getAttachmentWithUrl('skripsi_diagram', diagram.id, 'image')

    return { ...diagram, imageUrl: stored?.url ?? null, blobId: blob.id }
  }

  // attachmentService uploads from a path, so the generated bytes go through a
  // temp file that is removed either way.
  static async storeImage({ diagramId, buffer, mimeType }) {
    const extension = mimeType === 'image/jpeg' ? 'jpg' : 'png'
    const filePath = path.join(os.tmpdir(), `skripsi-diagram-${diagramId}-${Date.now()}.${extension}`)

    try {
      fs.writeFileSync(filePath, buffer)

      return await attachmentService.uploadAndAttach({
        filePath,
        recordType: 'skripsi_diagram',
        recordId: diagramId,
        name: 'image',
        folder: UPLOAD_FOLDER,
      })
    } finally {
      if (fs.existsSync(filePath)) fs.unlinkSync(filePath)
    }
  }
}
